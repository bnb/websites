// property tests: generated inputs, checked against rules that hold for any
// input, like "the record is valid against the lexicons" and "never throws"
import fs from 'node:fs';
import path from 'node:path';
import * as fc from 'fast-check';
import { describe, expect, it } from 'vitest';
import { imageInfo } from './bytes';
import { toContent, type Block } from './leaflet';
import { pinAtUri } from './pin';
import { normalizeSiteUrl } from './site';
import { localPaths } from './sync';
import { convert, pending } from './test/markdown';
import { assertValidRecord } from './test/records';
import { useTmpDir } from './test/tmp';

const IMAGE_TYPE = /^image\/(png|gif|webp|jpeg)$/;
const SEGMENT = /^[a-z0-9-]{1,8}$/;
const TRAILING_SLASH = /\/$/;
// characters a markdown link destination in <angle brackets> can't hold as
// themselves: the brackets, a backslash or & (escapes and entities), or # ? %
// (which mean something in a URL, as they would in the page's HTML)
const NOT_IN_FILENAME = /[<>\\&#?%/\r\n\0]/;

const tmp = useTmpDir();

// a document record around converted blocks, with images and posts as their
// fallbacks, the way they'd be published without network access
const recordOf = ({ blocks, textContent }: { blocks: Block[]; textContent: string }) => ({
	$type: 'site.standard.document',
	site: 'at://did:plc:prop/site.standard.publication/3lpub2222222',
	title: 'Generated',
	publishedAt: '2026-01-01T00:00:00.000Z',
	textContent,
	content: toContent(blocks.map((block) => ('pending' in block ? block.fallback : block)))
});

// markdown and HTML syntax, mixed with arbitrary text so the pieces land in
// every kind of context
const SYNTAX = [
	'# ',
	'### ',
	'- ',
	'* ',
	'1. ',
	'3) ',
	'  ',
	'    ',
	'> ',
	'**',
	'__',
	'_',
	'*',
	'`',
	'``',
	'~~',
	'[',
	'](',
	')',
	'](/a b)',
	'![',
	'![alt](pic.png)',
	'<',
	'>',
	'<div>',
	'</div>',
	'<p>',
	'</p>',
	'<br>',
	'<span>',
	'</span>',
	'<img src="x.png" alt="',
	'">',
	'<script>',
	'</script>',
	'<style>',
	'</style>',
	'<svg>',
	'</svg>',
	'<pre>',
	'</pre>',
	'<!--',
	'-->',
	'&amp;',
	'&lt;',
	'&mdash;',
	'&#',
	'&#x',
	';',
	'&nbsp;',
	'```',
	'```js',
	'~~~',
	'---',
	'***',
	'| a | b |',
	'| --- | --- |',
	'\\',
	'https://bsky.app/profile/a.example/post/3kabc',
	'https://example.com/x',
	'💖',
	'é',
	'é',
	'👩‍👩‍👧',
	'中文',
	'שלום',
	'\t',
	' ',
	'\r'
];
const piece = fc.oneof(
	{ weight: 3, arbitrary: fc.constantFrom(...SYNTAX) },
	{ weight: 2, arbitrary: fc.string({ unit: 'grapheme', maxLength: 12 }) },
	{
		weight: 1,
		arbitrary: fc
			.tuple(fc.boolean(), fc.integer({ min: 0, max: 0x7fffffff }))
			.map(([hex, code]) => (hex ? `&#x${code.toString(16)};` : `&#${code};`))
	}
);
const separator = fc.constantFrom('', ' ', '\n', '\n\n', '\n  ', '\n> ');
const markdown = fc
	.array(fc.tuple(piece, separator), { maxLength: 40 })
	.map((parts) => parts.flat().join(''));

describe('properties', () => {
	it('converts any markdown to a valid record', () => {
		fc.assert(
			fc.property(markdown, fc.boolean(), (source, breaks) => {
				const converted = convert(source, {
					baseUrl: 'https://example.com/posts/generated/',
					breaks
				});
				assertValidRecord('site.standard.document', recordOf(converted));
			}),
			{ numRuns: 300 }
		);
	});

	// file headers imageInfo recognizes, so generated bytes reach every branch
	const HEADERS = [
		[0x89, 0x50, 0x4e, 0x47],
		[...Buffer.from('GIF89a')],
		[...Buffer.from('RIFF'), 0, 0, 0, 0, ...Buffer.from('WEBPVP8 ')],
		[...Buffer.from('RIFF'), 0, 0, 0, 0, ...Buffer.from('WEBPVP8L')],
		[...Buffer.from('RIFF'), 0, 0, 0, 0, ...Buffer.from('WEBPVP8X')],
		[0xff, 0xd8, 0xff, 0xc0],
		[0xff, 0xd8, 0xff, 0xe1, 0x00, 0x20, ...Buffer.from('Exif\0\0MM')],
		[0xff, 0xd8, 0xff, 0xe1, 0x00, 0x20, ...Buffer.from('Exif\0\0II')],
		[]
	];

	it('reads image headers without throwing, and only reports whole dimensions', () => {
		fc.assert(
			fc.property(
				fc.constantFrom(...HEADERS),
				fc.uint8Array({ maxLength: 120 }),
				(header, rest) => {
					const info = imageInfo(Buffer.from([...header, ...rest]));
					if (info !== null) {
						expect(info.mimeType).toMatch(IMAGE_TYPE);
						expect(Number.isInteger(info.width) && info.width >= 0).toBe(true);
						expect(Number.isInteger(info.height) && info.height >= 0).toBe(true);
					}
				}
			),
			{ numRuns: 2000 }
		);
	});

	it('normalizes spellings of the same site URL to the same URL', () => {
		const segment = fc.stringMatching(SEGMENT);
		fc.assert(
			fc.property(fc.domain(), fc.array(segment, { maxLength: 3 }), (host, segments) => {
				const url = `https://${host}${segments.map((s) => `/${s}`).join('')}`;
				const normal = normalizeSiteUrl(url);
				for (const spelling of [
					`${url}/`,
					url.replace(host, host.toUpperCase()),
					`${url}/?ref=feed#top`
				]) {
					expect(normalizeSiteUrl(spelling)).toBe(normal);
				}
				expect(normal).not.toMatch(TRAILING_SLASH);
			})
		);
	});

	const FILENAME_CHAR = fc
		.string({ unit: 'grapheme', minLength: 1, maxLength: 1 })
		.filter((char) => !NOT_IN_FILENAME.test(char));

	it("leads a local image's src back to its file, whatever it's called", () => {
		fc.assert(
			fc.property(fc.string({ unit: FILENAME_CHAR, minLength: 1, maxLength: 16 }), (name) => {
				fc.pre(name.trim() === name && name !== '.' && name !== '..');
				const file = `${name}.png`;
				const [image] = convert(`![x](<${file}>)`, {
					baseUrl: 'https://example.com/posts/p/'
				}).blocks;
				expect(pending(image)?.pending, JSON.stringify(file)).toBe('image');
				const doc = { inputPath: path.join(tmp.path, 'post.md'), url: '/posts/p/' };
				expect(localPaths(pending(image).src!, doc, { inputDir: tmp.path })[0]).toBe(
					path.join(tmp.path, file)
				);
			}),
			{ numRuns: 300 }
		);
	});

	const value = fc.string({ maxLength: 12 }).map((text) => JSON.stringify(text));
	const frontMatterLine = fc.oneof(
		fc.tuple(fc.constantFrom('title', 'description', 'layout'), value),
		fc.constant(['atUri', '""']),
		fc.constant(['atUri', '']),
		fc.constant(['tags', '[a, b]'])
	);

	it('pins by adding (or filling in) one atUri line, and leaves the rest of the file alone', () => {
		const URI = 'at://did:plc:prop/site.standard.document/3lpin2222222';
		const LINE = `atUri: "${URI}"`;
		fc.assert(
			fc.property(
				fc.option(fc.uniqueArray(frontMatterLine, { selector: ([key]) => key })),
				fc.constantFrom('\n', '\r\n'),
				fc.boolean(),
				fc.string({ maxLength: 40 }),
				(lines, newline, bom, body) => {
					fc.pre(!body.startsWith('---'));
					const BOM = bom ? '﻿' : '';
					const kept = (lines ?? [])
						.filter(([key]) => key !== 'atUri')
						.map(([key, v]) => `${key}: ${v}`);
					const source =
						BOM +
						(lines === null
							? ''
							: ['---', ...(lines ?? []).map(([key, v]) => `${key}: ${v}`), '---', ''].join(
									newline
								)) +
						body;
					const inputPath = path.join(tmp.path, 'pin.md');
					fs.writeFileSync(inputPath, source);
					pinAtUri({ inputPath, uri: URI });
					const pinned = fs.readFileSync(inputPath, 'utf8');

					// new lines end the way the file's lines already do
					const eol = source.includes('\r\n') ? '\r\n' : '\n';
					expect(pinned.startsWith(`${BOM}---`)).toBe(true);
					expect(pinned.endsWith(`${eol}---${eol}${body}`)).toBe(true);
					const matter = pinned.slice(BOM.length, -`${eol}---${eol}${body}`.length);
					const pinnedLines = matter.split(eol).slice(1);
					// exactly one atUri, the new one, with every other line kept in order
					expect(pinnedLines.filter((line) => line.startsWith('atUri'))).toEqual([LINE]);
					expect(pinnedLines.filter((line) => !line.startsWith('atUri'))).toEqual(kept);
				}
			),
			{ numRuns: 300 }
		);
	});
});
